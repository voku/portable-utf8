<?php

// Preserve mapping order and values; no compressor or new runtime dependency.
$write = in_array('--write', $argv, true);
$root = dirname(__DIR__, 2) . '/src/voku/helper/data/';
$map = include $root . 'emoji.php';
$rows = [];
foreach ($map as $name => $value) {
    if (strpos($name, 'CHARACTER_') !== 0 || strpbrk($name . $value, "\t\n\r") !== false) {
        throw new RuntimeException('Unsupported emoji row: ' . $name);
    }
    $rows[] = substr($name, 10) . "\t" . $value;
}
$packed = str_replace(['\\', "'"], ['\\\\', "\\'"], implode("\n", $rows));
$output = <<<'LOADER'
<?php

// Generated by build/footprint/compact.php. Order is part of the emoji contract.
return (static function (): array {
    $data = [];
    foreach (\explode("\n", 'ROWS') as $row) {
        [$name, $value] = \explode("\t", $row, 2);
        $data['CHARACTER_' . $name] = $value;
    }

    return $data;
})();
LOADER;
$output = str_replace('ROWS', $packed, $output) . "\n";
$outputs = [
    'emoji.php' => $output,
    'chr.php' => "<?php return \\array_map('chr', \\range(0, 255));\n",
    'ord.php' => "<?php return ['' => 0] + \\array_flip(\\array_map('chr', \\range(0, 255)));\n",
];
$changed = 0;
foreach ($outputs as $name => $contents) {
    $file = $root . $name;
    if ($contents !== file_get_contents($file)) {
        ++$changed;
        if ($write) {
            file_put_contents($file, $contents);
        }
    }
}
echo $changed . ' representations ' . ($write ? 'written' : 'need regeneration') . PHP_EOL;
exit(!$write && $changed !== 0 ? 1 : 0);
